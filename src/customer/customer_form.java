    private void load_table() throws SQLException {
        // Membuat tampilan model tabel
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID Customer");
        model.addColumn("Customer Name");
        model.addColumn("Phone Number");
        model.addColumn("Address");
        
        try (Connection conn = getConnection();
             Statement stmt = conn.createStatement();
             java.sql.ResultSet rs = stmt.executeQuery("SELECT * FROM customer")) {
            
            // Mengisi baris tabel dengan data dari database
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_customer"),
                    rs.getString("nama_customer"),
                    rs.getString("no_telp"),
                    rs.getString("alamat")
                });
            }
            Tabel_Informasi.setModel(model);
        } catch (java.sql.SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }
