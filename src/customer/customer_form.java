    private void BTN_KirimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_KirimActionPerformed
        // Aksi Insert Data (CREATE)
        try (Connection conn = getConnection();
             PreparedStatement pst = conn.prepareStatement("INSERT INTO customer (nama_customer, no_telp, alamat) VALUES (?, ?, ?)")) {
            
            pst.setString(1, Form_Nama.getText());
            pst.setString(2, Form_Nomor.getText());
            pst.setString(3, Form_Alamat.getText());
            
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Disimpan!");
            load_table();
            clear_form();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage());
        } catch (java.sql.SQLException ex) {
            System.getLogger(customer_form.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_BTN_KirimActionPerformed

    private void BTN_EditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_EditActionPerformed
        // Aksi Update Data (UPDATE)
        if (selectedId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Silakan pilih data dari tabel terlebih dahulu!");
            return;
        }
        
        try (Connection conn = getConnection();
             PreparedStatement pst = conn.prepareStatement("UPDATE customer SET nama_customer=?, no_telp=?, alamat=? WHERE id_customer=?")) {
            
            pst.setString(1, Form_Nama.getText());
            pst.setString(2, Form_Nomor.getText());
            pst.setString(3, Form_Alamat.getText());
            pst.setString(4, selectedId);
            
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Diubah!");
            load_table();
            clear_form();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal mengubah data: " + e.getMessage());
        } catch (java.sql.SQLException ex) {
            System.getLogger(customer_form.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_BTN_EditActionPerformed

    private void BTN_HapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_HapusActionPerformed
        // Aksi Hapus Data (DELETE)
        if (selectedId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Silakan pilih data dari tabel terlebih dahulu!");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try (Connection conn = getConnection();
                 PreparedStatement pst = conn.prepareStatement("DELETE FROM customer WHERE id_customer=?")) {
                
                pst.setString(1, selectedId);
                pst.executeUpdate();
                JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Dihapus!");
                load_table();
                clear_form();
                
            } catch (SQLException e) {
                // Menangkap pesan error jika ID customer sedang dipakai di tabel penjualan (ON DELETE RESTRICT)
                JOptionPane.showMessageDialog(this, "Gagal menghapus data: Kemungkinan data ini sedang digunakan pada riwayat transaksi.\n" + e.getMessage());
            } catch (java.sql.SQLException ex) {
                System.getLogger(customer_form.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
        }
    }//GEN-LAST:event_BTN_HapusActionPerformed

    private void Tabel_InformasiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_Tabel_InformasiMouseClicked
        // Menampilkan data ke textfield ketika baris di klik
        int baris = Tabel_Informasi.rowAtPoint(evt.getPoint());
        if (baris > -1) {
            selectedId = Tabel_Informasi.getValueAt(baris, 0).toString(); // Ambil ID yang tersembunyi/ditampilkan
            Form_Nama.setText(Tabel_Informasi.getValueAt(baris, 1) != null ? Tabel_Informasi.getValueAt(baris, 1).toString() : "");
            Form_Nomor.setText(Tabel_Informasi.getValueAt(baris, 2) != null ? Tabel_Informasi.getValueAt(baris, 2).toString() : "");
            Form_Alamat.setText(Tabel_Informasi.getValueAt(baris, 3) != null ? Tabel_Informasi.getValueAt(baris, 3).toString() : "");
        }
    }//GEN-LAST:event_Tabel_InformasiMouseClicked

