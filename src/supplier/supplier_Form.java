    private void BTN_EditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_EditActionPerformed
        // 1. Cek apakah ada baris tabel yang dipilih
        int selectedRowIndex = Tabel_Informasi.getSelectedRow();

        if (selectedRowIndex < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan klik/pilih data pada tabel yang ingin diubah terlebih dahulu!");
            return;
        }

        // 2. Ambil ID Supplier dari kolom pertama (index 0) pada baris yang dipilih
        String idSupplier = Tabel_Informasi.getValueAt(selectedRowIndex, 0).toString();

        // 3. Validasi agar form tidak dikosongkan saat mengedit
        if (Form_Nama.getText().trim().isEmpty() || 
            Form_Nomor.getText().trim().isEmpty() || 
            Form_Alamat.getText().trim().isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(this, "Semua data (Nama, No Telp, Alamat) tidak boleh kosong!");
            return;
        }

        // 4. Konfirmasi pengubahan data
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "Yakin ingin mengubah data supplier ini?", "Konfirmasi Ubah",
            javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            try {
                java.sql.Connection conn = Koneksi.koneksi.ConnectionDB();

                // 5. Query UPDATE (id_supplier digunakan sebagai patokan di bagian WHERE)
                String sql = "UPDATE supplier SET nama_supplier = ?, no_telp = ?, alamat = ? WHERE id_supplier = ?";

                java.sql.PreparedStatement pstmt = conn.prepareStatement(sql);
                pstmt.setString(1, Form_Nama.getText());
                pstmt.setString(2, Form_Nomor.getText());
                pstmt.setString(3, Form_Alamat.getText());
                pstmt.setString(4, idSupplier); // Memasukkan ID dari tabel

                pstmt.executeUpdate();
                javax.swing.JOptionPane.showMessageDialog(null, "Data Berhasil Diubah!");

                // 6. Refresh tabel dan bersihkan form
                TampilData();
                Form_Nama.setText("");
                Form_Nomor.setText("");
                Form_Alamat.setText("");

            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(null, "Gagal mengubah data: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_BTN_EditActionPerformed
   
    
