    private void TampilData() {
      // 1. Membuat model untuk kolom tabel
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel() {
        @Override
        public boolean isCellEditable(int row, int column) {
            // Mengembalikan nilai false agar semua baris dan kolom terkunci
            return false;
        }
    };
        model.addColumn("ID Supplier"); 
        model.addColumn("Nama Supplier");
        model.addColumn("No Telepon");
        model.addColumn("Alamat");
        
        // 2. Memasukkan model ke variabel JTable Anda
        // PENTING: Ganti 'TabelSupplier' dengan nama variabel JTable Anda di NetBeans
        Tabel_Informasi.setModel(model);
        
        try {
        // 3. Memanggil koneksi (Pastikan nama class koneksi Anda sesuai)
        java.sql.Connection conn = Koneksi.koneksi.ConnectionDB(); 
        java.sql.Statement stat = conn.createStatement();

        // 4. Query untuk mengambil semua data dari tabel (Sesuaikan nama tabel Anda)
        String sql = "SELECT * FROM supplier"; 
        java.sql.ResultSet res = stat.executeQuery(sql);

        // 5. Looping untuk memasukkan data baris demi baris
        while (res.next()) {
            model.addRow(new Object[]{
                // Nama kolom dalam getString("") harus SAMA PERSIS dengan di database
                res.getString("id_supplier"), 
                res.getString("nama_supplier"),
                res.getString("no_telp"),
                res.getString("alamat")
            });
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Gagal Menampilkan Data: " + e.getMessage());
        }
    }
